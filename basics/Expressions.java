package basics;

public class Expressions {
    public static void main(String[] args) {
        // Expressions: Operands (values) & Operators (arithmetic)
        // Operators: +, -, *, /, %
        int friends = 10;
        friends = friends / 4;

        double balance = 100.5;
        balance /= 2;

        System.out.println("No. of friends: " + friends);
        System.out.println("Wallet balance: Rs. " + balance);
    }
}
